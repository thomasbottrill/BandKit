import assert from "node:assert/strict";
import { paperTexture, paperFadeMask, syncPaperSurface } from "../src/content/paper-surface.js";
import fs from "node:fs";
import { defaultState } from "../src/content/state.js";
assert.equal(defaultState.appearance.paperTexture, false, "Existing finishes are unchanged");
assert.equal(defaultState.appearance.paperTextureStrength, 100);
assert.equal(defaultState.appearance.paperFibreStrength, 70);
assert.equal(defaultState.appearance.paperMottleStrength, 20);
assert.equal(defaultState.appearance.paperGrainSize, 240);
assert.equal(paperTexture(65), paperTexture(65), "Grain stays static");
assert.equal(paperTexture(1000), paperTexture(100));
assert.equal(paperTexture(-1), paperTexture(0));
const texture = decodeURIComponent(paperTexture(65));
assert.equal((texture.match(/data:image\/svg\+xml/g) || []).length, 2, "Fine detail and paper structure use independent layers");
assert.ok(texture.includes('id="micro"') && texture.includes('id="mottle"'), "Paper combines fine grain with broad mottling");
assert.ok(texture.includes('stroke="#fff"') && texture.includes('stroke="#000"'), "Fibres have restrained light and dark relief");
assert.ok(texture.includes('stroke-linecap="round"'), "Fibres have soft rounded ends");
assert.ok(!texture.includes("NaN"));
assert.equal(paperTexture("invalid"), paperTexture(65));
const layers = (...values) => [...paperTexture(...values).matchAll(/url\("data:image\/svg\+xml,([^"]+)"\)/g)].map(match => decodeURIComponent(match[1]));
assert.equal(layers(65, 0, 65)[0], layers(65, 100, 65)[0], "Fibres do not change grain");
assert.equal(layers(0, 65, 65)[1], layers(100, 65, 65)[1], "Grain does not change fibres or mottling");
assert.ok(layers(65, 0, 65)[1].includes('<g opacity="0"'), "Fibres can be disabled independently");
assert.ok(layers(65, 65, 0)[1].includes('opacity="0" filter="url(#mottle)"'), "Mottling can be disabled independently");
assert.equal(paperTexture(80), paperTexture(80, 80, 80), "Existing combined strength remains the default for all layers");
const paints = [{ width: "1040px", height: "244px", bottom: "-18px", filter: "blur(28px)", opacity: "0.98" }, { width: "940px", height: "280px", bottom: "-54px", filter: "blur(9px)", opacity: "1" }];
const mask = decodeURIComponent(paperFadeMask(1000, 228, paints));
assert.ok(mask.includes('viewBox="-192 -192 1384 612"'), "Mask has room outside the layer bounds for feathering");
assert.ok(mask.includes('stdDeviation="28"') && mask.includes('stdDeviation="9"'), "Grain uses both actual backing blur radii");
assert.ok(mask.includes('M-20 246V221.6A520 219.6'), "Grain follows the backing shoulder geometry");
assert.ok(!mask.includes("NaN"));
const css = fs.readFileSync(new URL("../src/styles/hub/glass.css", import.meta.url), "utf8");
const playerSurface = fs.readFileSync(new URL("../src/content/runtime/player-surface.js", import.meta.url), "utf8");
assert.match(playerSurface, /background-color: var\(--paper-fade-color\);\s*background-image: var\(--paper-texture\);\s*background-blend-mode: soft-light;\s*mix-blend-mode: normal;/, "Paper colour and texture composite before the fade mask, avoiding pale edges");
assert.ok(playerSurface.includes("layer.hidden = !fade || paperFade"), "Paper fade does not double-composite backing alpha");
for (const source of [css, playerSurface]) {
  assert.match(source, /background-size:\s*192px 192px,\s*calc\(var\(--(?:hub-)?paper-grain-size,\s*160px\)\s*\*\s*2\.4\)/, "Fine grain stays fixed while paper structure scales");
}
assert.match(css, /\.hub-panel\.is-paper :is\(\.hub-content, \.hub-header, \.hub-panel-shortcuts\)\s*\{\s*background: transparent !important;/);
const properties = new Map();
const surface = () => ({ classes: new Set(), get classList() { return { toggle: (key, enabled) => enabled ? this.classes.add(key) : this.classes.delete(key) }; } });
const r = { $host: { style: { setProperty: (key, value) => properties.set(key, value) } }, $player: surface(), $panel: surface(), $djDrawer: surface(), $onboardingDialog: surface() };
const appearance = { paperTexture: true, paperTextureStrength: 80, frostedGlass: false };
syncPaperSurface(r, appearance);
assert.ok(r.$player.classes.has("is-paper"));
assert.ok(r.$panel.classes.has("is-paper"));
assert.ok(r.$djDrawer.classes.has("is-paper"));
assert.equal(properties.get("--hub-paper-texture"), paperTexture(80));
assert.equal(properties.get("--hub-paper-grain-size"), "384px");
appearance.paperGrainSize = 200;
syncPaperSurface(r, appearance);
assert.equal(properties.get("--hub-paper-grain-size"), "320px");
assert.equal(properties.get("--hub-paper-texture"), paperTexture(80), "Size never changes texture strength");
assert.equal(appearance.paperFibreStrength, 80, "Saved legacy strength migrates to fibres");
assert.equal(appearance.paperMottleStrength, 80, "Saved legacy strength migrates to mottling");
appearance.paperTextureStrength = 20;
syncPaperSurface(r, appearance);
assert.equal(properties.get("--hub-paper-texture"), paperTexture(20, 80, 80), "Adjusting grain leaves the other strengths unchanged");
appearance.paperFibreStrength = 0;
appearance.paperMottleStrength = 35;
syncPaperSurface(r, appearance);
assert.equal(properties.get("--hub-paper-texture"), paperTexture(20, 0, 35));
appearance.paperGrainSize = 999;
syncPaperSurface(r, appearance);
assert.equal(appearance.paperGrainSize, 400);
appearance.frostedGlass = true;
syncPaperSurface(r, appearance);
assert.equal(r.$player.classes.has("is-paper"), false, "Glass never composites paper grain");
assert.equal(properties.get("--hub-paper-texture"), "none");
const fresh = { paperTexture: true };
syncPaperSurface(r, fresh);
assert.equal(properties.get("--hub-paper-texture"), paperTexture(100, 70, 20), "New paper settings use the approved layer strengths");
assert.equal(fresh.paperGrainSize, 240);
const settingsSource = fs.readFileSync(new URL("../src/content/music-bar-settings.js", import.meta.url), "utf8");
assert.ok(settingsSource.includes("defaultValue: PAPER_DEFAULTS[key]"), "Reset uses each layer's new default");
for (const group of ["hub-paper-controls", "hub-glass-controls", "hub-corner-controls", "hub-dynamic-color-options"]) {
  assert.ok(settingsSource.includes(`${group} hub-settings-dependent-options`), `${group} uses shared dependent indentation`);
}
console.log("Paper finish: defaults, bounded strength, deterministic grain, shared surfaces and glass switching passed");
